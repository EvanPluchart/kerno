/// What a document is of: the facts of its header and the objects read.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Document {
    pub title: String,
    pub engine: Engine,
    /// The server's product and version (`PostgreSQL 17.2`).
    pub server: String,
    pub database: String,
    /// `None` on engines without schemas (MySQL, MariaDB, SQLite).
    pub schema: Option<String>,
    /// `YYYY-MM-DD`.
    pub date: String,
    pub side: Side,
}

/// The server as a document names it: its product and version, without
/// what PostgreSQL's banner adds (` on <platform>, compiled by …`).
pub fn server_label(engine: Engine, server: &ServerInfo) -> String {
    let named = server.named(engine);
    match named.split_once(" on ") {
        Some((product, _)) => product.to_string(),
        None => named,
    }
}

/// A document's title before the user changes it: `database.schema`, or
/// the database alone.
pub fn default_title(database: &str, schema: Option<&str>) -> String {
    match schema {
        Some(schema) => format!("{database}.{schema}"),
        None => database.to_string(),
    }
}

/// The file name the save panel starts with: `<schema>-schema.<ext>`.
pub fn file_name(schema: &str, format: Format) -> String {
    let stem: String = schema
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || "-_.".contains(c) {
                c
            } else {
                '_'
            }
        })
        .collect();
    let stem = stem.trim_start_matches('.');
    let stem = if stem.is_empty() { "schema" } else { stem };
    format!("{stem}-schema.{}", format.extension())
}

/// Today's date in UTC, `YYYY-MM-DD`.
pub fn today() -> String {
    let seconds = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs() as i64);
    let (year, month, day) = crate::format::civil_from_days(seconds.div_euclid(86_400));
    format!("{year:04}-{month:02}-{day:02}")
}

/// The tables and views of a schema a document can pick, by name, in the
/// order the server lists them: what [`load`] reads (partitions and
/// foreign tables left out).
pub fn pickable(objects: &SchemaObjects) -> Vec<(String, RelationKind)> {
    objects
        .relations
        .iter()
        .filter(|relation| !relation.is_partition && relation.kind != RelationKind::ForeignTable)
        .map(|relation| (relation.name.clone(), relation.kind))
        .collect()
}

/// What to read.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Pick {
    /// Tables and views, by name.
    pub relations: BTreeSet<String>,
    /// Also the schema's functions, procedures, sequences and types, and
    /// the triggers of the tables picked.
    pub code: bool,
}

/// Reads the objects `pick` names of `schema`: the structure of each table
/// and the DDL of the rest, eight at a time, telling `progress` after each
/// (the compare's read). Stops with [`crate::Error::Cancelled`] once
/// `cancel` is set. Rows are never read.
pub async fn load(
    session: Arc<dyn Session>,
    schema: &str,
    pick: &Pick,
    progress: impl Fn(erd::Progress) + Send,
    cancel: &AtomicBool,
) -> Result<Side> {
    let mut listing = compare::listing(&session, schema).await?;
    listing
        .tables
        .retain(|(table, _)| pick.relations.contains(&table.name));
    listing.others.retain(|object| match object {
        ObjectRef::Relation(table, _) => pick.relations.contains(&table.name),
        ObjectRef::Trigger { table, .. } => pick.code && pick.relations.contains(&table.name),
        _ => pick.code,
    });
    compare::read(session, schema, listing, progress, cancel).await
}

// The model as the writers read it ---------------------------------------------

/// A table of the document.
struct Table<'a> {
    table: &'a TableRef,
    kind: RelationKind,
    structure: &'a TableStructure,
}

/// An object written by its DDL: a view, a routine, a sequence, a type, a
/// trigger.
struct Code<'a> {
    kind: Kind,
    name: String,
    ddl: &'a str,
}

/// The kinds of the code sections, in their order.
const CODE_KINDS: [Kind; 5] = [
    Kind::Function,
    Kind::Procedure,
    Kind::Sequence,
    Kind::Type,
    Kind::Trigger,
];

impl Document {
    /// The tables, by name.
    fn tables(&self) -> Vec<Table<'_>> {
        let mut tables: Vec<Table> = self
            .side
            .objects
            .iter()
            .filter_map(|object| match (&object.object, &object.definition) {
                (ObjectRef::Relation(table, kind), Definition::Table(structure)) => Some(Table {
                    table,
                    kind: *kind,
                    structure,
                }),
                _ => None,
            })
            .collect();
        tables.sort_by(|a, b| a.table.name.cmp(&b.table.name));
        tables
    }

    /// The objects of `kinds` written by their DDL, by kind then name.
    fn code(&self, kinds: &[Kind]) -> Vec<Code<'_>> {
        let mut code: Vec<Code> = self
            .side
            .objects
            .iter()
            .filter_map(|object| {
                let kind = Kind::of(&object.object).filter(|kind| kinds.contains(kind))?;
                let Definition::Ddl(ddl) = &object.definition else {
                    return None;
                };
                Some(Code {
                    kind,
                    name: compare::shown_name(&object.object),
                    ddl,
                })
            })
            .collect();
        code.sort_by(|a, b| (a.kind, &a.name).cmp(&(b.kind, &b.name)));
        code
    }

    fn views(&self) -> Vec<Code<'_>> {
        self.code(&[Kind::View, Kind::MaterializedView])
    }

    /// "4 tables, 2 views and 3 functions"; "nothing" when empty.
    fn counts(&self) -> String {
        let mut parts = Vec::new();
        let tables = self.tables().len();
        if tables > 0 {
            parts.push(count(tables, "table", "tables"));
        }
        for kind in [Kind::View, Kind::MaterializedView]
            .into_iter()
            .chain(CODE_KINDS)
        {
            let n = self.code(&[kind]).len();
            if n > 0 {
                parts.push(count(n, kind.label(), &kind.plural().to_lowercase()));
            }
        }
        match parts.as_slice() {
            [] => "nothing".into(),
            [one] => one.clone(),
            [head @ .., last] => format!("{} and {last}", head.join(", ")),
        }
    }

    /// The header's facts, as label and value.
    fn facts(&self) -> Vec<(&'static str, String)> {
        let mut facts = vec![
            ("Server", self.server.clone()),
            ("Database", self.database.clone()),
        ];
        if let Some(schema) = &self.schema {
            facts.push(("Schema", schema.clone()));
        }
        facts.push(("Date", self.date.clone()));
        facts.push(("Contents", self.counts()));
        facts
    }

    /// The diagram of the tables.
    fn diagram(&self) -> erd::Diagram {
        let schema = self.side.schema.clone();
        erd::Diagram::new(
            schema,
            self.tables()
                .into_iter()
                .map(|table| (table.table.clone(), table.structure.clone()))
                .collect(),
        )
    }
}

fn count(n: usize, one: &str, many: &str) -> String {
    format!("{n} {}", if n == 1 { one } else { many })
}

/// A column as the documents show it.
struct ColumnRow<'a> {
    column: &'a ColumnInfo,
    /// `PK`, `FK`, `UQ`, joined by spaces.
    keys: String,
    /// The default, or how the value is generated.
    default: Option<String>,
}

fn column_rows(structure: &TableStructure) -> Vec<ColumnRow<'_>> {
    let in_key: BTreeSet<&str> = structure
        .foreign_keys
        .iter()
        .flat_map(|key| key.columns.iter().map(String::as_str))
        .collect();
    let unique: BTreeSet<&str> = structure
        .constraints
        .iter()
        .filter(|constraint| constraint.kind == ConstraintKind::Unique)
        .map(|constraint| constraint.columns.as_slice())
        .chain(
            structure
                .indexes
                .iter()
                .filter(|index| index.unique && !index.primary && index.predicate.is_none())
                .map(|index| index.columns.as_slice()),
        )
        .filter_map(|columns| match columns {
            [one] => Some(one.as_str()),
            _ => None,
        })
        .collect();
    structure
        .columns
        .iter()
        .map(|column| {
            let mut keys = Vec::new();
            if column.primary_key_position.is_some() {
                keys.push("PK");
            }
            if in_key.contains(column.name.as_str()) {
                keys.push("FK");
            }
            if column.primary_key_position.is_none() && unique.contains(column.name.as_str()) {
                keys.push("UQ");
            }
            let default = match &column.generation {
                Some(ColumnGeneration::IdentityAlways) => Some("identity (always)".into()),
                Some(ColumnGeneration::IdentityByDefault) => Some("identity".into()),
                Some(ColumnGeneration::AutoIncrement) => Some("auto increment".into()),
                Some(ColumnGeneration::Stored(expression)) => {
                    Some(format!("generated: {expression} (stored)"))
                }
                Some(ColumnGeneration::Virtual(expression)) => {
                    Some(format!("generated: {expression}"))
                }
                None => present(&column.default).map(str::to_string),
            };
            ColumnRow {
                column,
                keys: keys.join(" "),
                default,
            }
        })
        .collect()
}

/// The primary key: its name when the engine gives one, and its columns in
/// key order.
fn primary_key(structure: &TableStructure) -> Option<(Option<&str>, Vec<&str>)> {
    if let Some(constraint) = structure
        .constraints
        .iter()
        .find(|constraint| constraint.kind == ConstraintKind::PrimaryKey)
        .filter(|constraint| !constraint.columns.is_empty())
    {
        return Some((
            Some(constraint.name.as_str()).filter(|name| !name.is_empty()),
            constraint.columns.iter().map(String::as_str).collect(),
        ));
    }
    let mut columns: Vec<(u32, &str)> = structure
        .columns
        .iter()
        .filter_map(|column| {
            column
                .primary_key_position
                .map(|at| (at, column.name.as_str()))
        })
        .collect();
    columns.sort_unstable();
    (!columns.is_empty()).then(|| (None, columns.into_iter().map(|(_, name)| name).collect()))
}

fn constraint_label(kind: ConstraintKind) -> &'static str {
    match kind {
        ConstraintKind::PrimaryKey => "primary key",
        ConstraintKind::Unique => "unique",
        ConstraintKind::Check => "check",
        ConstraintKind::Exclusion => "exclusion",
    }
}

/// A referenced table as a document names it: alone in its own schema,
/// qualified in another.
fn referenced(doc: &Document, table: &TableRef) -> String {
    if table.schema == doc.side.schema {
        table.name.clone()
    } else {
        format!("{}.{}", table.schema, table.name)
    }
}

fn kind_label(kind: RelationKind) -> Option<&'static str> {
    match kind {
        RelationKind::PartitionedTable => Some("partitioned table"),
        _ => None,
    }
}

/// Every line break a reader may take as one.
fn is_break(c: char) -> bool {
    matches!(
        c,
        '\n' | '\r' | '\u{b}' | '\u{c}' | '\u{85}' | '\u{2028}' | '\u{2029}'
    )
}

/// `text` cut at every line break (`\r\n` counts once).
fn lines(text: &str) -> Vec<String> {
    text.replace("\r\n", "\n")
        .split(is_break)
        .map(str::to_string)
        .collect()
}

/// `text` on one line: line breaks and other control characters become
/// spaces.
fn one_line(text: &str) -> String {
    text.chars()
        .map(|c| {
            if c.is_control() || is_break(c) {
                ' '
            } else {
                c
            }
        })
        .collect()
}

/// Writes `doc` in `format`; `dialect` writes the SQL.
pub fn render(doc: &Document, format: Format, options: &Options, dialect: &dyn Dialect) -> String {
    match format {
        Format::Dbml => to_dbml(doc),
        Format::Markdown => to_markdown(doc),
        Format::Sql => to_sql(doc, dialect),
        Format::Mermaid => erd::to_mermaid(&doc.diagram()),
        Format::Html => html::to_html(doc, options),
    }
}

