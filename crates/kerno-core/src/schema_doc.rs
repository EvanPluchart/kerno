/// A document's format.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Format {
    Dbml,
    Markdown,
    Sql,
    Mermaid,
    Html,
}

impl Format {
    /// In the order the dialog shows them.
    pub const ALL: [Format; 5] = [
        Format::Html,
        Format::Markdown,
        Format::Dbml,
        Format::Sql,
        Format::Mermaid,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Format::Dbml => "DBML",
            Format::Markdown => "Markdown",
            Format::Sql => "SQL",
            Format::Mermaid => "Mermaid",
            Format::Html => "HTML",
        }
    }

    pub fn extension(self) -> &'static str {
        match self {
            Format::Dbml => "dbml",
            Format::Markdown => "md",
            Format::Sql => "sql",
            Format::Mermaid => "mmd",
            Format::Html => "html",
        }
    }

    /// What the format is for, in plain words.
    pub fn purpose(self) -> &'static str {
        match self {
            Format::Html => {
                "One page to read or print: the diagram, then every table with its columns, \
                 keys and indexes. Opens in any browser, asks the network for nothing."
            }
            Format::Markdown => {
                "A data dictionary as text: for a wiki, a pull request, or an AI assistant."
            }
            Format::Dbml => {
                "Tables, columns and references in DBML, to draw on dbdiagram.io or publish \
                 with dbdocs."
            }
            Format::Sql => {
                "The statements that create the objects picked, in an order that runs: to keep \
                 the schema in git."
            }
            Format::Mermaid => {
                "The diagram as a Mermaid erDiagram, for Markdown files that render Mermaid."
            }
        }
    }
}

/// How an HTML document looks.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum Style {
    /// Kerno's light theme, the lockup and a "Generated by Kerno" line.
    #[default]
    KernoLight,
    /// Kerno's dark theme on screen; it prints as the light one.
    KernoDark,
    /// Black on white, no brand colour, no logo, no "generated by" line.
    Plain,
}

impl Style {
    pub const ALL: [Style; 3] = [Style::KernoLight, Style::KernoDark, Style::Plain];

    pub fn label(self) -> &'static str {
        match self {
            Style::KernoLight => "Kerno light",
            Style::KernoDark => "Kerno dark",
            Style::Plain => "Plain",
        }
    }
}

