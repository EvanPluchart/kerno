//! Schema documents (K31): the structure of a schema, all of it or the
//! tables and views picked, written as a document to read or to keep. DBML
//! (dbdiagram.io, dbdocs), Markdown (a data dictionary), SQL (the DDL in an
//! order that runs), Mermaid (the diagram) and HTML (one self-contained
//! file, in Kerno's light or dark style or plain black on white).
//!
//! Structure only: no row is read, and a document never names the host,
//! the port, the user, a database file's path or the connection, unless the
//! user typed one of them as its title. Names, comments, defaults and DDL
//! come from the server: they are untrusted text, escaped for each format
//! by the one writer of that format (`dbml_*`, `md_*`, [`html`]'s `esc`,
//! [`compare::commented`] for SQL comments, the diagram's own rules for
//! Mermaid and SVG).
//!
//! What is read is the schema compare's model ([`compare::Side`], read by
//! [`compare::read`]), so the SQL is the compare's script against an empty
//! schema, in the same order.

