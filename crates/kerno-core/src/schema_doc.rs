/// Words DBML reads as its own: a name spelled so is quoted.
const DBML_WORDS: [&str; 22] = [
    "table",
    "tablegroup",
    "tablepartial",
    "ref",
    "enum",
    "project",
    "note",
    "indexes",
    "as",
    "pk",
    "primary",
    "key",
    "null",
    "not",
    "unique",
    "increment",
    "default",
    "delete",
    "update",
    "check",
    "true",
    "false",
];

/// A name as DBML takes it: bare when it is a plain word, else between
/// double quotes with `\` and `"` escaped, on one line.
fn dbml_name(name: &str) -> String {
    let plain = name.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !DBML_WORDS.contains(&name.to_ascii_lowercase().as_str());
    if plain {
        return name.to_string();
    }
    format!(
        "\"{}\"",
        one_line(name).replace('\\', "\\\\").replace('"', "\\\"")
    )
}

/// A type as DBML takes it: bare when it is a word with an optional size
/// (`varchar(40)`, `int[]`), else quoted as a name.
fn dbml_type(data_type: &str) -> String {
    let plain = data_type.starts_with(|c: char| c.is_ascii_alphabetic())
        && data_type
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "_(),[]".contains(c));
    if plain {
        data_type.to_string()
    } else {
        format!(
            "\"{}\"",
            one_line(data_type)
                .replace('\\', "\\\\")
                .replace('"', "\\\"")
        )
    }
}

/// A DBML string: between single quotes with `\` and `'` escaped, or
/// between triple quotes when it holds line breaks (every `'` escaped, so
/// no `'''` can end it early).
fn dbml_string(text: &str) -> String {
    let escape = |line: &str| {
        line.chars()
            .filter(|c| !c.is_control() || *c == '\t')
            .collect::<String>()
            .replace('\\', "\\\\")
            .replace('\'', "\\'")
    };
    let lines = lines(text);
    if lines.len() == 1 {
        return format!("'{}'", escape(&lines[0]));
    }
    let body: Vec<String> = lines.iter().map(|line| escape(line)).collect();
    format!("'''\n{}\n'''", body.join("\n"))
}

/// A column's default as DBML takes it: a number, `true`, `false` or
/// `null` as they are; a string literal as a string; anything else as an
/// expression between backticks, or as a string when it holds a backtick
/// or a line break.
fn dbml_default(text: &str) -> String {
    let text = text.trim();
    let lower = text.to_ascii_lowercase();
    if matches!(lower.as_str(), "true" | "false" | "null") {
        return lower;
    }
    if text.parse::<f64>().is_ok()
        && text
            .chars()
            .all(|c| c.is_ascii_digit() || ".-+eE".contains(c))
    {
        return text.to_string();
    }
    // `'text'`, or PostgreSQL's `'text'::type`.
    if let Some(rest) = text.strip_prefix('\'') {
        let end = rest.rfind('\'');
        if let Some(end) = end {
            let (inner, after) = (&rest[..end], &rest[end + 1..]);
            let cast = after.is_empty()
                || after.strip_prefix("::").is_some_and(|ty| {
                    !ty.is_empty()
                        && ty
                            .chars()
                            .all(|c| c.is_ascii_alphanumeric() || " _\"[]".contains(c))
                });
            if cast && !inner.replace("''", "").contains('\'') {
                return dbml_string(&inner.replace("''", "'"));
            }
        }
    }
    if text.contains('`') || text.chars().any(|c| c.is_control() || is_break(c)) {
        dbml_string(text)
    } else {
        format!("`{text}`")
    }
}

/// `ON DELETE` / `ON UPDATE` as DBML spells it, when it is one DBML knows.
fn dbml_action(action: &str) -> Option<String> {
    let action = action.trim().to_ascii_lowercase();
    [
        "cascade",
        "restrict",
        "set null",
        "set default",
        "no action",
    ]
    .contains(&action.as_str())
    .then_some(action)
}

fn to_dbml(doc: &Document) -> String {
    let qualified = |table: &TableRef| match &doc.schema {
        Some(_) => format!("{}.{}", dbml_name(&table.schema), dbml_name(&table.name)),
        None => dbml_name(&table.name),
    };
    let columns = |names: &[String]| match names {
        [one] => dbml_name(one),
        many => format!(
            "({})",
            many.iter()
                .map(|name| dbml_name(name))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    };
    let mut out = String::new();
    let note: Vec<String> = doc
        .facts()
        .into_iter()
        .map(|(label, value)| format!("{label}: {value}"))
        .collect();
    let _ = writeln!(out, "Project {} {{", dbml_name(&doc.title));
    let _ = writeln!(out, "  database_type: {}", dbml_string(doc.engine.label()));
    let _ = writeln!(out, "  Note: {}", dbml_string(&note.join("\n")));
    out.push_str("}\n");
    let tables = doc.tables();
    let shown: BTreeSet<&TableRef> = tables.iter().map(|table| table.table).collect();
    for Table {
        table, structure, ..
    } in &tables
    {
        let _ = writeln!(out, "\nTable {} {{", qualified(table));
        let primary = primary_key(structure).map(|(_, columns)| columns);
        let single_pk = primary.as_ref().filter(|columns| columns.len() == 1);
        for row in column_rows(structure) {
            let column = row.column;
            let mut settings = Vec::new();
            if single_pk.is_some_and(|pk| pk[0] == column.name) {
                settings.push("pk".to_string());
            } else if !column.nullable {
                settings.push("not null".into());
            }
            if row.keys.contains("UQ") {
                settings.push("unique".into());
            }
            match &column.generation {
                Some(
                    ColumnGeneration::AutoIncrement
                    | ColumnGeneration::IdentityAlways
                    | ColumnGeneration::IdentityByDefault,
                ) => settings.push("increment".into()),
                Some(
                    ColumnGeneration::Stored(expression) | ColumnGeneration::Virtual(expression),
                ) => settings.push(format!(
                    "note: {}",
                    dbml_string(&format!("generated: {expression}"))
                )),
                None => {
                    if let Some(default) = present(&column.default) {
                        settings.push(format!("default: {}", dbml_default(default)));
                    }
                }
            }
            if let Some(comment) = present(&column.comment) {
                settings.push(format!("note: {}", dbml_string(comment)));
            }
            let settings = if settings.is_empty() {
                String::new()
            } else {
                format!(" [{}]", settings.join(", "))
            };
            let _ = writeln!(
                out,
                "  {} {}{settings}",
                dbml_name(&column.name),
                dbml_type(&column.data_type)
            );
        }
        let mut indexes = Vec::new();
        if let Some(primary) = primary.as_ref().filter(|columns| columns.len() > 1) {
            let names: Vec<String> = primary.iter().map(|name| name.to_string()).collect();
            indexes.push(format!("{} [pk]", columns(&names)));
        }
        for index in &structure.indexes {
            if index.primary || index.columns.is_empty() {
                continue;
            }
            let mut settings = Vec::new();
            if index.unique {
                settings.push("unique".to_string());
            }
            if !index.name.is_empty() {
                settings.push(format!("name: {}", dbml_string(&index.name)));
            }
            if matches!(index.method.as_str(), "btree" | "hash") {
                settings.push(format!("type: {}", index.method));
            }
            let names = columns(&index.columns);
            indexes.push(if settings.is_empty() {
                names
            } else {
                format!("{names} [{}]", settings.join(", "))
            });
        }
        if !indexes.is_empty() {
            out.push_str("\n  indexes {\n");
            for index in indexes {
                let _ = writeln!(out, "    {index}");
            }
            out.push_str("  }\n");
        }
        if let Some(comment) = present(&structure.comment) {
            let _ = writeln!(out, "\n  Note: {}", dbml_string(comment));
        }
        out.push_str("}\n");
    }
    let mut refs = String::new();
    for Table {
        table, structure, ..
    } in &tables
    {
        for key in &structure.foreign_keys {
            if !shown.contains(&key.referenced_table) {
                continue;
            }
            let side = |table: &TableRef, names: &[String]| match names {
                [one] => format!("{}.{}", qualified(table), dbml_name(one)),
                many => format!("{}.{}", qualified(table), columns(many)),
            };
            let settings: Vec<String> = [("delete", &key.on_delete), ("update", &key.on_update)]
                .into_iter()
                .filter_map(|(on, action)| {
                    dbml_action(action)
                        .filter(|action| action != "no action")
                        .map(|action| format!("{on}: {action}"))
                })
                .collect();
            let _ = writeln!(
                refs,
                "Ref {}: {} > {}{}",
                dbml_name(&key.name),
                side(table, &key.columns),
                side(&key.referenced_table, &key.referenced_columns),
                if settings.is_empty() {
                    String::new()
                } else {
                    format!(" [{}]", settings.join(", "))
                }
            );
        }
    }
    if !refs.is_empty() {
        out.push('\n');
        out.push_str(&refs);
    }
    out
}

