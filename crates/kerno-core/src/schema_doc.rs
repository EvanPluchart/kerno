/// ASCII punctuation Markdown gives no meaning inside a line: written as
/// it is, except where noted in [`md_text`].
const MD_LITERAL: &str = ",.-()'\"/;=?%{}+";

/// Text as Markdown reads it literally: every ASCII punctuation character
/// that could start markup escaped (emphasis, code, links, images, HTML,
/// entities, pipes, autolinks through `:`, `@` and `www.`, math), the first
/// character of a line when it is punctuation (headings, lists, quotes,
/// rules), and the `.` or `)` of a leading number (ordered lists); control
/// characters dropped. Line breaks become `<br>` in a table cell, hard
/// breaks elsewhere.
fn md_text(text: &str, in_table: bool) -> String {
    let escaped: Vec<String> = lines(text)
        .iter()
        .map(|line| {
            let line = if in_table {
                line.as_str()
            } else {
                line.trim_start()
            };
            let mut out = String::with_capacity(line.len());
            for c in line.chars() {
                if c == '\t' {
                    out.push(' ');
                    continue;
                }
                if c.is_control() {
                    continue;
                }
                let escape = c.is_ascii_punctuation()
                    && (!MD_LITERAL.contains(c)
                        || out.is_empty()
                        || (c == '.' && out.to_ascii_lowercase().ends_with("www"))
                        || (matches!(c, '.' | ')')
                            && !in_table
                            && out.chars().all(|d| d.is_ascii_digit())));
                if escape {
                    out.push('\\');
                }
                out.push(c);
            }
            out
        })
        .collect();
    escaped.join(if in_table { "<br>" } else { "\\\n" })
}

/// A name, type or definition as inline code, on one line, between enough
/// backticks that none inside ends it. In a table cell, text with a pipe or
/// a backslash is escaped text instead: a table splits its rows on a pipe
/// even inside code, and `\|` there would not hold.
fn md_code(text: &str, in_table: bool) -> String {
    let text = one_line(text);
    if text.trim().is_empty() {
        return String::new();
    }
    if in_table && (text.contains('|') || text.contains('\\')) {
        return md_text(&text, true);
    }
    let longest = text
        .split(|c| c != '`')
        .map(str::len)
        .max()
        .unwrap_or_default();
    let fence = "`".repeat(longest + 1);
    if text.starts_with('`') || text.ends_with('`') {
        format!("{fence} {text} {fence}")
    } else {
        format!("{fence}{text}{fence}")
    }
}

/// `text` in a fenced code block whose fence is longer than any run of
/// backticks inside it, so no line of it can close the block.
fn md_block(text: &str, language: &str) -> String {
    let longest = text
        .split(|c| c != '`')
        .map(str::len)
        .max()
        .unwrap_or_default();
    let fence = "`".repeat((longest + 1).max(3));
    format!(
        "{fence}{language}\n{}\n{fence}",
        lines(text.trim_end()).join("\n")
    )
}

fn md_table(out: &mut String, header: &[&str], rows: Vec<Vec<String>>) {
    let _ = writeln!(out, "| {} |", header.join(" | "));
    let _ = writeln!(out, "|{}", "---|".repeat(header.len()));
    for row in rows {
        let _ = writeln!(out, "| {} |", row.join(" | "));
    }
    out.push('\n');
}

fn to_markdown(doc: &Document) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# {}\n", md_text(&one_line(&doc.title), false));
    for (label, value) in doc.facts() {
        // Names as code, the rest as text.
        let value = match label {
            "Database" | "Schema" => md_code(&value, false),
            _ => md_text(&value, false),
        };
        let _ = writeln!(out, "- **{label}:** {value}");
    }
    out.push('\n');
    let tables = doc.tables();
    if !tables.is_empty() {
        out.push_str("## Tables\n\n");
    }
    for Table {
        table,
        kind,
        structure,
    } in &tables
    {
        let _ = writeln!(
            out,
            "### {}{}\n",
            md_code(&table.name, false),
            kind_label(*kind).map_or(String::new(), |kind| format!(" ({kind})"))
        );
        if let Some(comment) = present(&structure.comment) {
            let _ = writeln!(out, "{}\n", md_text(comment, false));
        }
        let rows = column_rows(structure)
            .into_iter()
            .map(|row| {
                vec![
                    md_code(&row.column.name, true),
                    md_code(&row.column.data_type, true),
                    if row.column.nullable { "yes" } else { "no" }.into(),
                    row.default
                        .as_deref()
                        .map_or(String::new(), |default| md_code(default, true)),
                    row.keys,
                    present(&row.column.comment)
                        .map_or(String::new(), |comment| md_text(comment, true)),
                ]
            })
            .collect();
        md_table(
            &mut out,
            &["Column", "Type", "Nullable", "Default", "Key", "Comment"],
            rows,
        );
        if let Some((name, columns)) = primary_key(structure) {
            let columns: Vec<String> = columns
                .iter()
                .map(|column| md_code(column, false))
                .collect();
            let _ = writeln!(
                out,
                "**Primary key**{}: {}\n",
                name.map_or(String::new(), |name| format!(" {}", md_code(name, false))),
                columns.join(", ")
            );
        }
        let constraints: Vec<Vec<String>> = structure
            .constraints
            .iter()
            .filter(|constraint| constraint.kind != ConstraintKind::PrimaryKey)
            .map(|constraint| {
                vec![
                    md_code(&constraint.name, true),
                    constraint_label(constraint.kind).into(),
                    md_code(&constraint.definition, true),
                ]
            })
            .collect();
        if !constraints.is_empty() {
            out.push_str("**Constraints**\n\n");
            md_table(&mut out, &["Name", "Kind", "Definition"], constraints);
        }
        let indexes: Vec<Vec<String>> = structure
            .indexes
            .iter()
            .filter(|index| !index.primary)
            .map(|index| {
                let columns = if index.columns.is_empty() {
                    index
                        .definition
                        .as_deref()
                        .map_or(String::new(), |definition| md_code(definition, true))
                } else {
                    index
                        .columns
                        .iter()
                        .map(|column| md_code(column, true))
                        .collect::<Vec<_>>()
                        .join(", ")
                };
                vec![
                    md_code(&index.name, true),
                    columns,
                    if index.unique { "yes" } else { "no" }.into(),
                    md_code(&index.method, true),
                ]
            })
            .collect();
        if !indexes.is_empty() {
            out.push_str("**Indexes**\n\n");
            md_table(&mut out, &["Name", "Columns", "Unique", "Method"], indexes);
        }
        let keys: Vec<Vec<String>> = structure
            .foreign_keys
            .iter()
            .map(|key| {
                let names = |names: &[String]| {
                    names
                        .iter()
                        .map(|name| md_code(name, true))
                        .collect::<Vec<_>>()
                        .join(", ")
                };
                vec![
                    md_code(&key.name, true),
                    names(&key.columns),
                    format!(
                        "{} ({})",
                        md_code(&referenced(doc, &key.referenced_table), true),
                        names(&key.referenced_columns)
                    ),
                    md_text(&key.on_delete, true),
                    md_text(&key.on_update, true),
                ]
            })
            .collect();
        if !keys.is_empty() {
            out.push_str("**Foreign keys**\n\n");
            md_table(
                &mut out,
                &["Name", "Columns", "References", "On delete", "On update"],
                keys,
            );
        }
    }
    let sections = [
        ("Views", doc.views()),
        (
            "Routines, sequences, types and triggers",
            doc.code(&CODE_KINDS),
        ),
    ];
    for (heading, objects) in sections {
        if objects.is_empty() {
            continue;
        }
        let _ = writeln!(out, "## {heading}\n");
        for object in objects {
            let _ = writeln!(
                out,
                "### {} ({})\n\n{}\n",
                md_code(&object.name, false),
                object.kind.label(),
                md_block(object.ddl, "sql")
            );
        }
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

