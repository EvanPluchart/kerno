/// The DDL of the objects, in the order the compare's script runs them:
/// types and sequences, the tables without their foreign keys, their
/// constraints and keys, routines, views, triggers. A header of comment
/// lines says what it is.
fn to_sql(doc: &Document, dialect: &dyn Dialect) -> String {
    let mut out = String::new();
    out.push_str(&compare::commented(&one_line(&doc.title)));
    out.push('\n');
    for (label, value) in doc.facts() {
        out.push_str(&compare::commented(&format!("{label}: {value}")));
        out.push('\n');
    }
    out.push('\n');
    if doc.side.objects.is_empty() {
        out.push_str(&compare::commented("Nothing was picked."));
        out.push('\n');
        return out;
    }
    let empty = Side {
        schema: doc.side.schema.clone(),
        objects: Vec::new(),
    };
    let items = compare::compare(&doc.side, &empty, dialect, dialect);
    out.push_str(&compare::script(&items, |_| true, false));
    out
}

