//! A table as the form editor holds it, and what changed between it and the
//! table on the server. Pure: the statements are written by the dialect
//! ([`crate::Dialect::create_table_sql`], [`crate::Dialect::alter_table_sql`]).

use crate::schema::{ColumnGeneration, ColumnInfo, IndexInfo, TableRef, TableStructure};

/// A table as the form editor holds it. `original` names tie a draft item to
/// what exists on the server.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableDraft {
    /// Schema and name (the new name when renamed).
    pub table: TableRef,
    /// Table comment.
    pub comment: Option<String>,
    /// Columns, in display order.
    pub columns: Vec<ColumnDraft>,
    /// Indexes other than those that back a key constraint.
    pub indexes: Vec<IndexDraft>,
    /// Foreign keys from this table.
    pub foreign_keys: Vec<ForeignKeyDraft>,
    /// Primary key column names, in key order; empty for none.
    pub primary_key: Vec<String>,
}

/// A column of a [`TableDraft`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ColumnDraft {
    /// Name in the existing table; `None` for a new column.
    pub original: Option<String>,
    /// Name.
    pub name: String,
    /// Type as typed: `numeric(10,2)`, `varchar(190)`, `bigint unsigned`.
    pub data_type: String,
    /// Whether NULL is allowed.
    pub nullable: bool,
    /// Default as an SQL expression, as typed.
    pub default: Option<String>,
    /// Comment.
    pub comment: Option<String>,
    /// Whether and how the column numbers its rows.
    pub auto_increment: AutoIncrement,
    /// MySQL `ON UPDATE` expression, kept from [`ColumnInfo::on_update`] so
    /// that a rewritten definition does not lose it.
    pub on_update: Option<String>,
    /// MySQL / MariaDB `INVISIBLE`, kept from [`ColumnInfo::invisible`] so
    /// that a rewritten definition does not lose it.
    pub invisible: bool,
}

/// How a column of a [`TableDraft`] numbers its rows.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum AutoIncrement {
    /// It does not.
    #[default]
    Off,
    /// PostgreSQL `GENERATED BY DEFAULT AS IDENTITY` (or a `serial`),
    /// MySQL `AUTO_INCREMENT`.
    On,
    /// PostgreSQL `GENERATED ALWAYS AS IDENTITY`.
    Always,
}

impl AutoIncrement {
    /// Auto-increment turned `on` or not, for the column `original` was on
    /// the server: an identity keeps its kind when it is turned off and on
    /// again, a new one is [`AutoIncrement::On`].
    pub fn new(on: bool, original: Option<&ColumnInfo>) -> Self {
        match original.and_then(|column| column.generation.as_ref()) {
            _ if !on => Self::Off,
            Some(ColumnGeneration::IdentityAlways) => Self::Always,
            _ => Self::On,
        }
    }

    /// Whether the column numbers its rows.
    pub fn is_on(self) -> bool {
        self != Self::Off
    }
}

/// An index of a [`TableDraft`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IndexDraft {
    /// Name of the existing index; `None` for a new one.
    pub original: Option<String>,
    /// Name.
    pub name: String,
    /// Indexed columns, in order.
    pub columns: Vec<String>,
    /// Unique index.
    pub unique: bool,
}

/// A foreign key of a [`TableDraft`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeignKeyDraft {
    /// Name of the existing constraint; `None` for a new one.
    pub original: Option<String>,
    /// Constraint name.
    pub name: String,
    /// Referencing columns, in order.
    pub columns: Vec<String>,
    /// Referenced table.
    pub referenced_table: TableRef,
    /// Referenced columns, matching `columns` by position.
    pub referenced_columns: Vec<String>,
    /// One of [`REFERENTIAL_ACTIONS`].
    pub on_update: String,
    /// One of [`REFERENTIAL_ACTIONS`].
    pub on_delete: String,
}

/// Why the column order of an existing PostgreSQL table cannot change: the
/// editor's reason and the default dialect's refusal of
/// [`TableChange::MoveColumn`].
pub const CANNOT_MOVE_COLUMNS: &str = "PostgreSQL cannot move a column: its position is fixed \
                                       when the column is created. Recreate the table, or use a \
                                       view, to change the order.";

/// What a foreign key may do when the referenced row is updated or deleted.
pub const REFERENTIAL_ACTIONS: [&str; 5] = [
    "NO ACTION",
    "RESTRICT",
    "CASCADE",
    "SET NULL",
    "SET DEFAULT",
];

/// What changed, in the order the statements must run (see [`changes`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TableChange {
    /// Rename the table, within its schema.
    RenameTable {
        /// New name.
        to: String,
    },
    /// Set or remove (`None`) the table comment.
    SetTableComment(Option<String>),
    /// Drop the named foreign key.
    DropForeignKey(String),
    /// Drop the named index.
    DropIndex(String),
    /// Drop the primary key, named by its constraint (`PRIMARY` on MySQL).
    DropPrimaryKey(String),
    /// Drop the named column.
    DropColumn(String),
    /// Rename a column.
    RenameColumn {
        /// Current name.
        from: String,
        /// New name.
        to: String,
    },
    /// Add a column.
    AddColumn(ColumnDraft),
    /// Change a column's type, nullability, default, comment,
    /// auto-increment or `ON UPDATE`. `name` is the name after any [`TableChange::RenameColumn`].
    AlterColumn {
        /// Column name, renamed if it is.
        name: String,
        /// The column as it is.
        from: ColumnInfo,
        /// The column as it should be.
        to: ColumnDraft,
    },
    /// Put a column right after `after`, or first when `None` (MySQL and
    /// MariaDB: `FIRST` / `AFTER`). Comes after the other column changes, in
    /// the table's new order; it carries the column's whole definition,
    /// which the statement that moves it rewrites (it also replaces that
    /// column's [`TableChange::AddColumn`], [`TableChange::RenameColumn`] or
    /// [`TableChange::AlterColumn`] there). See [`CANNOT_MOVE_COLUMNS`].
    MoveColumn {
        /// Column name, renamed if it is.
        name: String,
        /// The column on the server; `None` for one this change set adds.
        from: Option<ColumnInfo>,
        /// The column as it should be.
        to: ColumnDraft,
        /// The column it follows; `None` for first.
        after: Option<String>,
    },
    /// Add a primary key on these columns.
    AddPrimaryKey(Vec<String>),
    /// Create an index.
    AddIndex(IndexDraft),
    /// Add a foreign key.
    AddForeignKey(ForeignKeyDraft),
}

impl From<&ColumnInfo> for ColumnDraft {
    /// The column as the form shows it. Identity, auto-increment and
    /// `serial` are all `auto_increment`, and their sequence default is not
    /// a default.
    fn from(column: &ColumnInfo) -> Self {
        let auto_increment = AutoIncrement::new(
            matches!(
                column.generation,
                Some(
                    ColumnGeneration::IdentityAlways
                        | ColumnGeneration::IdentityByDefault
                        | ColumnGeneration::AutoIncrement
                )
            ),
            Some(column),
        );
        Self {
            original: Some(column.name.clone()),
            name: column.name.clone(),
            data_type: column.data_type.clone(),
            nullable: column.nullable,
            default: column.default.clone().filter(|_| !auto_increment.is_on()),
            comment: column.comment.clone(),
            auto_increment,
            on_update: column.on_update.clone(),
            invisible: column.invisible,
        }
    }
}

impl TableDraft {
    /// A new table with one `id` auto-increment primary key column.
    pub fn new(table: TableRef) -> Self {
        Self {
            table,
            comment: None,
            columns: vec![ColumnDraft {
                original: None,
                name: "id".into(),
                data_type: "bigint".into(),
                nullable: false,
                default: None,
                comment: None,
                auto_increment: AutoIncrement::On,
                on_update: None,
                invisible: false,
            }],
            indexes: Vec::new(),
            foreign_keys: Vec::new(),
            primary_key: vec!["id".into()],
        }
    }

    /// The draft of an existing table, every item tied to what it is on
    /// the server.
    ///
    /// Indexes the draft cannot describe are left out, and so are never
    /// touched: those backing a key constraint, partial and expression
    /// indexes, other methods than b-tree, and an index named after one of
    /// the table's foreign keys (MySQL creates one for a key that needs it,
    /// and refuses to drop it while the key exists).
    pub fn from_structure(table: &TableRef, structure: &TableStructure) -> Self {
        let mut primary_key: Vec<(u32, &str)> = structure
            .columns
            .iter()
            .filter_map(|c| c.primary_key_position.map(|p| (p, c.name.as_str())))
            .collect();
        primary_key.sort_unstable();
        Self {
            table: table.clone(),
            comment: structure.comment.clone(),
            columns: structure.columns.iter().map(ColumnDraft::from).collect(),
            indexes: structure
                .indexes
                .iter()
                .filter(|index| is_editable(index, structure))
                .map(|index| IndexDraft {
                    original: Some(index.name.clone()),
                    name: index.name.clone(),
                    columns: index.columns.clone(),
                    unique: index.unique,
                })
                .collect(),
            foreign_keys: structure
                .foreign_keys
                .iter()
                .map(|key| ForeignKeyDraft {
                    original: Some(key.name.clone()),
                    name: key.name.clone(),
                    columns: key.columns.clone(),
                    referenced_table: key.referenced_table.clone(),
                    referenced_columns: key.referenced_columns.clone(),
                    on_update: key.on_update.clone(),
                    on_delete: key.on_delete.clone(),
                })
                .collect(),
            primary_key: primary_key
                .into_iter()
                .map(|(_, name)| name.to_string())
                .collect(),
        }
    }

    /// What is wrong with the draft, one sentence per problem; empty when
    /// it can be written as SQL.
    pub fn validate(&self) -> Vec<String> {
        let mut problems = Vec::new();
        if self.table.name.trim().is_empty() {
            problems.push("The table needs a name.".to_string());
        }
        if self.columns.is_empty() {
            problems.push("The table needs at least one column.".to_string());
        }
        let has_column = |name: &String| self.columns.iter().any(|c| &c.name == name);
        for (index, column) in self.columns.iter().enumerate() {
            let name = &column.name;
            if name.trim().is_empty() {
                problems.push(format!("Column {} has no name.", index + 1));
                continue;
            }
            if self.columns[..index].iter().any(|c| &c.name == name) {
                problems.push(format!("There are two columns named \"{name}\"."));
            }
            if column.data_type.trim().is_empty() {
                problems.push(format!("Column \"{name}\" has no type."));
            }
            if column.auto_increment.is_on() && column.nullable {
                problems.push(format!(
                    "Column \"{name}\" is auto-increment and cannot allow NULL."
                ));
            }
            if column.auto_increment.is_on() && present(&column.default).is_some() {
                problems.push(format!(
                    "Column \"{name}\" is auto-increment and cannot have a default."
                ));
            }
        }
        for name in &self.primary_key {
            match self.columns.iter().find(|c| &c.name == name) {
                None => problems.push(format!(
                    "The primary key names a column that does not exist: \"{name}\"."
                )),
                Some(column) if column.nullable => problems.push(format!(
                    "Column \"{name}\" is in the primary key and cannot allow NULL."
                )),
                Some(_) => {}
            }
        }
        for (position, index) in self.indexes.iter().enumerate() {
            let name = &index.name;
            if name.trim().is_empty() {
                problems.push(format!("Index {} has no name.", position + 1));
            } else if self.indexes[..position].iter().any(|i| &i.name == name) {
                problems.push(format!("There are two indexes named \"{name}\"."));
            }
            if index.columns.is_empty() {
                problems.push(format!("Index \"{name}\" has no column."));
            }
            for column in index.columns.iter().filter(|c| !has_column(c)) {
                problems.push(format!(
                    "Index \"{name}\" names a column that does not exist: \"{column}\"."
                ));
            }
        }
        for (position, key) in self.foreign_keys.iter().enumerate() {
            let name = &key.name;
            if name.trim().is_empty() {
                problems.push(format!("Foreign key {} has no name.", position + 1));
            } else if self.foreign_keys[..position]
                .iter()
                .any(|k| &k.name == name)
            {
                problems.push(format!("There are two foreign keys named \"{name}\"."));
            }
            if key.columns.is_empty() {
                problems.push(format!("Foreign key \"{name}\" has no column."));
            }
            for column in key.columns.iter().filter(|c| !has_column(c)) {
                problems.push(format!(
                    "Foreign key \"{name}\" names a column that does not exist: \"{column}\"."
                ));
            }
            if key.referenced_table.name.trim().is_empty() {
                problems.push(format!(
                    "Foreign key \"{name}\" does not say which table it references."
                ));
            }
            if key.columns.len() != key.referenced_columns.len() {
                problems.push(format!(
                    "Foreign key \"{name}\" has {} columns but references {}.",
                    key.columns.len(),
                    key.referenced_columns.len()
                ));
            }
            for action in [&key.on_update, &key.on_delete] {
                if !REFERENTIAL_ACTIONS.contains(&action.as_str()) {
                    problems.push(format!(
                        "Foreign key \"{name}\" has an unknown action \"{action}\"."
                    ));
                }
            }
        }
        problems
    }
}

/// Whether a [`TableDraft`] can describe `index` (see
/// [`TableDraft::from_structure`]).
fn is_editable(index: &IndexInfo, structure: &TableStructure) -> bool {
    !index.primary
        && !index.backs_constraint
        && index.predicate.is_none()
        && index.method.eq_ignore_ascii_case("btree")
        && index
            .columns
            .iter()
            .all(|name| structure.columns.iter().any(|c| &c.name == name))
        && !structure.foreign_keys.iter().any(|k| k.name == index.name)
}

/// `text` trimmed, `None` when blank: an empty default or comment typed in
/// a form is no default or comment.
pub fn present(text: &Option<String>) -> Option<&str> {
    text.as_deref().map(str::trim).filter(|t| !t.is_empty())
}

/// Whether the column must be altered to become `to` (its name aside).
pub fn column_differs(from: &ColumnDraft, to: &ColumnDraft) -> bool {
    !from
        .data_type
        .trim()
        .eq_ignore_ascii_case(to.data_type.trim())
        || from.nullable != to.nullable
        || present(&from.default) != present(&to.default)
        || present(&from.comment) != present(&to.comment)
        || from.auto_increment != to.auto_increment
        || present(&from.on_update) != present(&to.on_update)
        || from.invisible != to.invisible
}

/// What must change, in order, to turn the table `original` (with
/// `structure`) into `draft`: foreign keys, indexes and the primary key are
/// dropped first; then columns are dropped, renamed, added and altered;
/// then columns out of place are moved (as few as possible: see
/// [`out_of_place`]); then the primary key, indexes and foreign keys are
/// added; the comment and the table name come last. A renamed or redefined index or foreign
/// key is dropped and added again. A draft equal to the structure gives no
/// change.
pub fn changes(
    original: &TableRef,
    structure: &TableStructure,
    draft: &TableDraft,
) -> Vec<TableChange> {
    let existing = TableDraft::from_structure(original, structure);
    // Existing column names as they will be once the draft is applied; a
    // dropped column keeps its name, which no draft column has.
    let renamed = |name: &String| -> String {
        draft
            .columns
            .iter()
            .find(|c| c.original.as_ref() == Some(name))
            .map_or_else(|| name.clone(), |c| c.name.clone())
    };
    let renamed_all = |names: &[String]| names.iter().map(renamed).collect::<Vec<_>>();
    // A key on the table itself references its columns by name, as text:
    // it follows their renames (a name already typed as the new one stays).
    let draft_keys: Vec<ForeignKeyDraft> = draft
        .foreign_keys
        .iter()
        .map(|key| ForeignKeyDraft {
            referenced_columns: if &key.referenced_table == original {
                renamed_all(&key.referenced_columns)
            } else {
                key.referenced_columns.clone()
            },
            ..key.clone()
        })
        .collect();

    let same_index = |e: &IndexDraft, d: &IndexDraft| {
        d.original.as_ref() == Some(&e.name)
            && d.name == e.name
            && d.unique == e.unique
            && d.columns == renamed_all(&e.columns)
    };
    let same_key = |e: &ForeignKeyDraft, d: &ForeignKeyDraft| {
        // A key on the table itself follows its renamed columns at both ends.
        let referenced = if &e.referenced_table == original {
            renamed_all(&e.referenced_columns)
        } else {
            e.referenced_columns.clone()
        };
        d.original.as_ref() == Some(&e.name)
            && d.name == e.name
            && d.columns == renamed_all(&e.columns)
            && d.referenced_table == e.referenced_table
            && d.referenced_columns == referenced
            && d.on_update.eq_ignore_ascii_case(&e.on_update)
            && d.on_delete.eq_ignore_ascii_case(&e.on_delete)
    };
    let primary_key_changed = renamed_all(&existing.primary_key) != draft.primary_key;

    let mut out = Vec::new();
    for key in &existing.foreign_keys {
        if !draft_keys.iter().any(|d| same_key(key, d)) {
            out.push(TableChange::DropForeignKey(key.name.clone()));
        }
    }
    for index in &existing.indexes {
        if !draft.indexes.iter().any(|d| same_index(index, d)) {
            out.push(TableChange::DropIndex(index.name.clone()));
        }
    }
    if primary_key_changed && !existing.primary_key.is_empty() {
        let name = structure
            .constraints
            .iter()
            .find(|c| c.kind == crate::schema::ConstraintKind::PrimaryKey)
            .map_or_else(|| "PRIMARY".to_string(), |c| c.name.clone());
        out.push(TableChange::DropPrimaryKey(name));
    }

    let kept = |column: &ColumnInfo| {
        draft
            .columns
            .iter()
            .find(|d| d.original.as_ref() == Some(&column.name))
    };
    for column in &structure.columns {
        if kept(column).is_none() {
            out.push(TableChange::DropColumn(column.name.clone()));
        }
    }
    let existing_column = |draft: &ColumnDraft| {
        draft
            .original
            .as_ref()
            .and_then(|name| structure.columns.iter().find(|c| &c.name == name))
    };
    for column in &draft.columns {
        if let Some(from) = existing_column(column)
            && from.name != column.name
        {
            out.push(TableChange::RenameColumn {
                from: from.name.clone(),
                to: column.name.clone(),
            });
        }
    }
    for column in &draft.columns {
        if existing_column(column).is_none() {
            out.push(TableChange::AddColumn(ColumnDraft {
                original: None,
                ..column.clone()
            }));
        }
    }
    for column in &draft.columns {
        if let Some(from) = existing_column(column)
            && column_differs(&ColumnDraft::from(from), column)
        {
            out.push(TableChange::AlterColumn {
                name: column.name.clone(),
                from: from.clone(),
                to: column.clone(),
            });
        }
    }

    // Added columns land at the end: where the draft puts a column
    // elsewhere, it moves (Beekeeper #1341).
    let order: Vec<usize> = structure
        .columns
        .iter()
        .filter_map(|column| {
            draft
                .columns
                .iter()
                .position(|d| d.original.as_ref() == Some(&column.name))
        })
        .chain((0..draft.columns.len()).filter(|&at| existing_column(&draft.columns[at]).is_none()))
        .collect();
    for at in out_of_place(&order) {
        let column = &draft.columns[at];
        out.push(TableChange::MoveColumn {
            name: column.name.clone(),
            from: existing_column(column).cloned(),
            to: ColumnDraft {
                original: None,
                ..column.clone()
            },
            after: at
                .checked_sub(1)
                .map(|before| draft.columns[before].name.clone()),
        });
    }

    if primary_key_changed && !draft.primary_key.is_empty() {
        out.push(TableChange::AddPrimaryKey(draft.primary_key.clone()));
    }
    for index in &draft.indexes {
        if !existing.indexes.iter().any(|e| same_index(e, index)) {
            out.push(TableChange::AddIndex(index.clone()));
        }
    }
    for key in &draft_keys {
        if !existing.foreign_keys.iter().any(|e| same_key(e, key)) {
            out.push(TableChange::AddForeignKey(key.clone()));
        }
    }
    if present(&existing.comment) != present(&draft.comment) {
        out.push(TableChange::SetTableComment(
            present(&draft.comment).map(str::to_string),
        ));
    }
    if draft.table.name != original.name {
        out.push(TableChange::RenameTable {
            to: draft.table.name.clone(),
        });
    }
    out
}

/// The target positions, in increasing order, of the items that must move
/// for `order` (the target position of each item, listed in the current
/// order) to become `0..n`: all but those of a longest increasing run,
/// which stay put. Moving the others in target order, each right after its
/// new predecessor (or first), gives the target order.
pub fn out_of_place(order: &[usize]) -> Vec<usize> {
    // Patience sorting: `tails[k]` ends the best run of length k + 1 seen
    // so far (an index into `order`), `previous` links a run backwards.
    let mut tails: Vec<usize> = Vec::new();
    let mut previous = vec![None; order.len()];
    for (at, &value) in order.iter().enumerate() {
        let length = tails.partition_point(|&tail| order[tail] < value);
        previous[at] = length.checked_sub(1).map(|before| tails[before]);
        if length == tails.len() {
            tails.push(at);
        } else {
            tails[length] = at;
        }
    }
    let mut staying = vec![false; order.len()];
    let mut link = tails.last().copied();
    while let Some(at) = link {
        staying[order[at]] = true;
        link = previous[at];
    }
    (0..order.len())
        .filter(|&target| !staying[target])
        .collect()
}

