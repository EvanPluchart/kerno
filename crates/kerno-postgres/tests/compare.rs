//! The schema compare (K30; NAV-57, CM-21, CM-59, TOOL-22) on PostgreSQL:
//! two scratch schemas with known differences are compared, the script is
//! run on the target, and a second compare finds them identical. Runs
//! against the `kerno-postgres` container; skipped with a message when it
//! is down. The fixture schemas are never touched.

mod common;

use std::sync::Arc;
use std::sync::atomic::AtomicBool;

use common::{exec_ok, run};
use kerno_core::Session;
use kerno_core::compare::{self, Item, State};
use kerno_core::sql::split_statements;

const SOURCE: &str = "kerno_test_cmp_a";
const TARGET: &str = "kerno_test_cmp_b";

const SETUP: &[&str] = &[
    "CREATE SCHEMA kerno_test_cmp_a",
    "CREATE TYPE kerno_test_cmp_a.mood AS ENUM ('sad', 'happy')",
    "CREATE TABLE kerno_test_cmp_a.customers (id serial PRIMARY KEY, email text NOT NULL, \
     mood kerno_test_cmp_a.mood, CONSTRAINT customers_email_key UNIQUE (email))",
    "CREATE TABLE kerno_test_cmp_a.orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
     customer_id integer NOT NULL REFERENCES kerno_test_cmp_a.customers (id), \
     price numeric(12,2) NOT NULL DEFAULT 0, note text, \
     CONSTRAINT orders_price_check CHECK (price >= 0))",
    "CREATE INDEX orders_customer_idx ON kerno_test_cmp_a.orders (customer_id)",
    "CREATE TABLE kerno_test_cmp_a.lines (id integer PRIMARY KEY, \
     order_id integer NOT NULL REFERENCES kerno_test_cmp_a.orders (id), tags text[])",
    "CREATE INDEX lines_tags_idx ON kerno_test_cmp_a.lines USING gin (tags)",
    "CREATE VIEW kerno_test_cmp_a.big_orders AS \
     SELECT id, customer_id FROM kerno_test_cmp_a.orders WHERE customer_id > 100",
    "CREATE FUNCTION kerno_test_cmp_a.touch() RETURNS trigger LANGUAGE plpgsql AS \
     $$ BEGIN NEW.note := coalesce(NEW.note, 'new'); RETURN NEW; END $$",
    "CREATE TRIGGER orders_touch BEFORE INSERT ON kerno_test_cmp_a.orders \
     FOR EACH ROW EXECUTE FUNCTION kerno_test_cmp_a.touch()",
    "CREATE SCHEMA kerno_test_cmp_b",
    "CREATE TYPE kerno_test_cmp_b.mood AS ENUM ('sad', 'happy')",
    "CREATE TABLE kerno_test_cmp_b.customers (id serial PRIMARY KEY, email text, \
     mood kerno_test_cmp_b.mood)",
    "CREATE TABLE kerno_test_cmp_b.orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
     customer_id integer NOT NULL, price numeric(10,2) NOT NULL DEFAULT 0, legacy text, \
     CONSTRAINT orders_price_check CHECK (price > 0))",
    "CREATE VIEW kerno_test_cmp_b.big_orders AS \
     SELECT id, customer_id FROM kerno_test_cmp_b.orders WHERE customer_id > 50",
    "CREATE TABLE kerno_test_cmp_b.old_stuff (id integer PRIMARY KEY)",
    "CREATE VIEW kerno_test_cmp_b.old_view AS SELECT 1 AS one",
];

async fn read(session: &Arc<dyn Session>, schema: &str) -> compare::Side {
    compare::load(session.clone(), schema, |_| {}, &AtomicBool::new(false))
        .await
        .unwrap_or_else(|error| panic!("{schema}: {error}"))
}

async fn compared(source: &Arc<dyn Session>, target: &Arc<dyn Session>) -> Vec<Item> {
    // The target on the session's path, as `public` is: the server would
    // print its names unqualified and the source's qualified, unless the
    // compare enters each side's schema.
    exec_ok(target, &format!("SET search_path TO {TARGET}, public")).await;
    let (a, b) = (read(source, SOURCE).await, read(target, TARGET).await);
    compare::compare(&a, &b, source.dialect(), target.dialect())
}

fn states(items: &[Item]) -> Vec<(String, State)> {
    items
        .iter()
        .map(|item| (item.name.clone(), item.state))
        .collect()
}

/// K30: the differences are found, the script brings the target to the
/// source, and a second compare finds nothing left (drops asked for).
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn the_script_brings_the_target_to_the_source() {
    let Some(admin) = common::session().await else {
        return;
    };
    let cleanup: Vec<String> = [SOURCE, TARGET]
        .iter()
        .map(|schema| format!("DROP SCHEMA IF EXISTS {schema} CASCADE"))
        .collect();
    for sql in &cleanup {
        exec_ok(&admin, sql).await;
    }
    let outcome = tokio::spawn(async move {
        let session = common::session().await.expect("the server");
        for sql in SETUP {
            exec_ok(&session, sql).await;
        }
        let (source, target) = (
            common::session().await.expect("the server"),
            common::session().await.expect("the server"),
        );
        let items = compared(&source, &target).await;
        use State::*;
        assert_eq!(
            states(&items),
            [
                ("customers".into(), Different),
                ("lines".into(), OnlyInSource),
                ("old_stuff".into(), OnlyInTarget),
                ("orders".into(), Different),
                ("big_orders".into(), Different),
                ("old_view".into(), OnlyInTarget),
                ("touch".into(), OnlyInSource),
                ("mood".into(), Same),
                ("orders_touch on orders".into(), OnlyInSource),
            ]
        );
        let orders = items.iter().find(|item| item.name == "orders").unwrap();
        for difference in [
            "column `legacy` is only in the target",
            "column `note` is missing in the target",
            "column `price`: numeric(10,2) → numeric(12,2)",
            "index `orders_customer_idx` is missing in the target",
            "foreign key `orders_customer_id_fkey` is missing in the target",
            "check `orders_price_check`: CHECK (price > 0::numeric) → CHECK (price >= 0::numeric)",
        ] {
            assert!(
                orders.differences.iter().any(|d| d == difference),
                "{difference} in {:#?}",
                orders.differences
            );
        }

        let script = compare::script(&items, |_| true, true);
        assert!(!script.contains(SOURCE), "{script}");
        // As the query tab the script opens in enters the target schema.
        let runner = common::session().await.expect("the server");
        exec_ok(&runner, &format!("SET search_path TO {TARGET}, public")).await;
        for statement in split_statements(&script, runner.dialect().lex_rules()) {
            let sql = statement.text(&script);
            if let Err(error) = run(&runner, sql).await {
                panic!("{sql}: {error}\nin\n{script}");
            }
        }

        let items = compared(&source, &target).await;
        let left: Vec<_> = items
            .iter()
            .filter(|item| item.state != State::Same)
            .map(|item| (item.name.clone(), item.differences.clone()))
            .collect();
        assert!(left.is_empty(), "{left:#?}\n{script}");
        assert_eq!(
            compare::script(&items, |_| true, true),
            "-- Nothing to change: the objects picked are the same on both sides.\n"
        );
    })
    .await;
    let mut failed = Vec::new();
    for sql in &cleanup {
        if let Err(error) = run(&admin, sql).await {
            failed.push(format!("{sql}: {error}"));
        }
    }
    if let Err(error) = outcome {
        std::panic::resume_unwind(error.into_panic());
    }
    assert!(failed.is_empty(), "cleanup failed: {failed:#?}");
}
