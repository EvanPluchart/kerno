//! Test data for a table (K72, D-141) on PostgreSQL: a scratch table with every
//! common type, a primary key, a unique column, foreign keys to a second scratch
//! table, an enum and a generated column gets 1,000 rows in one transaction and
//! keeps every rule; the script of 1,000 more runs as it is written; a parent
//! without rows is refused before anything runs; a row the server refuses keeps
//! nothing. Everything lives in the scratch schema `kerno_test_k72`, dropped
//! before and after, also on a failure. Skipped when the container is down.

mod common;

use std::sync::Arc;
use std::sync::atomic::AtomicBool;

use common::{exec_ok, run, scalar};
use kerno_core::schema::TableRef;
use kerno_core::sql::split_statements;
use kerno_core::test_data::{self, Kind, Plan, Settings, Shape};
use kerno_core::{Session, TxState};

const TYPES: &str = "kerno_test_k72_types";
const REFUSALS: &str = "kerno_test_k72_refusals";

async fn session() -> Arc<dyn Session> {
    common::session().await.expect("the server")
}

/// Runs `body` with the scratch schema created, and drops it after, whether
/// `body` passed or panicked.
async fn in_scratch<F>(schema: &str, body: F)
where
    F: std::future::Future<Output = ()> + Send + 'static,
{
    let Some(admin) = common::session().await else {
        return;
    };
    let cleanup = format!("DROP SCHEMA IF EXISTS {schema} CASCADE");
    exec_ok(&admin, &cleanup).await;
    exec_ok(&admin, &format!("CREATE SCHEMA {schema}")).await;
    let outcome = tokio::spawn(body).await;
    let dropped = run(&admin, &cleanup).await;
    if let Err(error) = outcome {
        std::panic::resume_unwind(error.into_panic());
    }
    dropped.expect("the scratch schema dropped");
}

/// The plan the dialog starts with for `rows` rows of `table`.
async fn guessed_plan(session: &Arc<dyn Session>, schema: &str, table: &str, rows: u64) -> Plan {
    let facts = test_data::read(session.clone(), &TableRef::new(schema, table))
        .await
        .unwrap();
    let settings = Settings {
        rows,
        seed: 72,
        columns: test_data::guess(&facts),
    };
    Plan::new(&facts, &settings).unwrap()
}

async fn insert(session: &Arc<dyn Session>, plan: Plan) -> test_data::Report {
    let cancel = Arc::new(AtomicBool::new(false));
    test_data::insert(session.clone(), plan, |_| {}, cancel)
        .await
        .unwrap()
}

async fn every_type() {
    const SCHEMA: &str = TYPES;
    let admin = session().await;
    for sql in [
        format!("CREATE TYPE {SCHEMA}.mood AS ENUM ('sad', 'ok', 'happy')"),
        format!(
            "CREATE TABLE {SCHEMA}.kerno_test_k72_parent (id integer PRIMARY KEY, \
             code text UNIQUE NOT NULL)"
        ),
        format!(
            "INSERT INTO {SCHEMA}.kerno_test_k72_parent \
             SELECT n, 'p' || n FROM generate_series(1, 5) n"
        ),
        format!(
            "CREATE TABLE {SCHEMA}.kerno_test_k72_child (\
             id integer PRIMARY KEY, \
             email varchar(120) NOT NULL UNIQUE, \
             name text, \
             price numeric(8,2), \
             qty smallint NOT NULL, \
             big bigint, \
             ratio double precision, \
             flag boolean NOT NULL, \
             born date, \
             at timestamptz, \
             local_at timestamp, \
             t time, \
             u uuid NOT NULL, \
             doc jsonb, \
             j json, \
             mood {SCHEMA}.mood NOT NULL, \
             moods {SCHEMA}.mood[], \
             data bytea, \
             tags text[], \
             nums integer[], \
             bits bit(4), \
             span interval, \
             serial_n integer GENERATED BY DEFAULT AS IDENTITY, \
             parent_id integer NOT NULL REFERENCES {SCHEMA}.kerno_test_k72_parent (id), \
             parent_code text REFERENCES {SCHEMA}.kerno_test_k72_parent (code), \
             total numeric GENERATED ALWAYS AS (price * 2) STORED)"
        ),
    ] {
        exec_ok(&admin, &sql).await;
    }
    let facts = test_data::read(
        admin.clone(),
        &TableRef::new(SCHEMA, "kerno_test_k72_child"),
    )
    .await
    .unwrap();
    let guessed = test_data::guess(&facts);
    let kind = |name: &str| {
        let index = facts
            .structure
            .columns
            .iter()
            .position(|c| c.name == name)
            .unwrap();
        guessed[index].kind
    };
    assert_eq!(kind("id"), Kind::Sequence);
    assert_eq!(kind("email"), Kind::Shape(Shape::Email));
    assert_eq!(kind("mood"), Kind::OneOf);
    assert_eq!(kind("moods"), Kind::Array);
    assert_eq!(kind("parent_id"), Kind::Reference);
    assert_eq!(kind("parent_code"), Kind::Reference);
    assert_eq!(kind("serial_n"), Kind::Server);
    assert_eq!(kind("total"), Kind::Server);
    assert_eq!(facts.parents[0].len(), 5);

    let plan = guessed_plan(&admin, SCHEMA, "kerno_test_k72_child", 1000).await;
    let report = insert(&admin, plan).await;
    assert_eq!(report.failed, None);
    assert_eq!(report.inserted, 1000);
    assert_eq!(admin.tx_state(), TxState::Idle);
    let child = format!("{SCHEMA}.kerno_test_k72_child");
    assert_eq!(
        scalar(
            &admin,
            &format!(
                "SELECT concat_ws('/', count(*), count(DISTINCT id), count(DISTINCT lower(email)), \
                 min(id), count(name), count(*) FILTER (WHERE total = price * 2), \
                 count(DISTINCT mood), count(DISTINCT parent_id), count(serial_n)) FROM {child}"
            )
        )
        .await,
        // About 10 % of the names NULL; every price present is doubled in total.
        format!(
            "1000/1000/1000/1/{}/{}/3/5/1000",
            scalar(&admin, &format!("SELECT count(name) FROM {child}")).await,
            scalar(&admin, &format!("SELECT count(price) FROM {child}")).await
        )
    );
    let names: u64 = scalar(&admin, &format!("SELECT count(name) FROM {child}"))
        .await
        .parse()
        .unwrap();
    assert!((850..=950).contains(&names), "{names} names");
    assert_eq!(
        scalar(
            &admin,
            &format!(
                "SELECT count(*) FROM {child} c JOIN {SCHEMA}.kerno_test_k72_parent p \
                 ON p.id = c.parent_id WHERE c.qty BETWEEN 1 AND 1000 \
                 AND coalesce(c.born BETWEEN '2020-01-01' AND '2026-12-31', true) \
                 AND coalesce(length(c.bits::text) = 4, true) \
                 AND coalesce(cardinality(c.tags) <= 3, true)"
            )
        )
        .await,
        "1000"
    );

    // The script of 1,000 more, read again: the sequence and the unique
    // email start beyond the rows there. It runs as written.
    let plan = guessed_plan(&admin, SCHEMA, "kerno_test_k72_child", 1000).await;
    let script = plan
        .script(admin.dialect(), "1,000 rows of test data")
        .unwrap();
    for literal in [
        &format!("INSERT INTO \"{SCHEMA}\".\"kerno_test_k72_child\" (\"id\", \"email\""),
        "(1001, '",
        "decode('",
        "1001@example.",
    ] {
        assert!(script.contains(literal), "{literal} in {}", &script[..2000]);
    }
    assert!(!script.contains("\"total\""));
    for statement in split_statements(&script, admin.dialect().lex_rules()) {
        let sql = statement.text(&script);
        if let Err(error) = run(&admin, sql).await {
            panic!("{sql}: {error}");
        }
    }
    assert_eq!(
        scalar(
            &admin,
            &format!("SELECT count(DISTINCT email) || '/' || max(id) FROM {child}")
        )
        .await,
        "2000/2000"
    );
}

/// K72: 1,000 generated rows of every common type insert in one transaction
/// and keep the table's rules; the script of 1,000 more runs as written.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_thousand_rows_of_every_type_insert_and_keep_the_rules() {
    in_scratch(TYPES, every_type()).await;
}

async fn refusals() {
    const SCHEMA: &str = REFUSALS;
    let admin = session().await;
    for sql in [
        format!("CREATE TABLE {SCHEMA}.kerno_test_k72_empty (id integer PRIMARY KEY)"),
        format!(
            "CREATE TABLE {SCHEMA}.kerno_test_k72_orphan (id integer PRIMARY KEY, \
             empty_id integer NOT NULL REFERENCES {SCHEMA}.kerno_test_k72_empty (id))"
        ),
        format!(
            "CREATE TABLE {SCHEMA}.kerno_test_k72_checked (id integer PRIMARY KEY, \
             price numeric(8,2) NOT NULL CONSTRAINT kerno_test_k72_cheap CHECK (price < 500))"
        ),
    ] {
        exec_ok(&admin, &sql).await;
    }
    // A parent without rows: said before anything runs.
    let facts = test_data::read(
        admin.clone(),
        &TableRef::new(SCHEMA, "kerno_test_k72_orphan"),
    )
    .await
    .unwrap();
    let settings = Settings {
        rows: 10,
        seed: 1,
        columns: test_data::guess(&facts),
    };
    assert_eq!(
        Plan::new(&facts, &settings).unwrap_err(),
        format!(
            "“{SCHEMA}.kerno_test_k72_empty” has no rows, and “empty_id” must hold one of its \
             keys: add rows there first."
        )
    );
    // A row the server refuses: its number and the server's words, and
    // nothing kept.
    let facts = test_data::read(
        admin.clone(),
        &TableRef::new(SCHEMA, "kerno_test_k72_checked"),
    )
    .await
    .unwrap();
    assert!(
        test_data::notes(&facts)
            .iter()
            .any(|note| note.contains("price < "))
    );
    let plan = guessed_plan(&admin, SCHEMA, "kerno_test_k72_checked", 1000).await;
    let first_bad = plan
        .values()
        .position(|row| {
            let price = test_data::shown(&row.unwrap()[1]);
            price.parse::<f64>().unwrap() >= 500.0
        })
        .unwrap() as u64
        + 1;
    let report = insert(&admin, plan).await;
    let failure = report.failed.expect("a refused row");
    assert_eq!(report.inserted, 0);
    assert_eq!(failure.row, first_bad);
    assert!(
        failure.message.contains("kerno_test_k72_cheap"),
        "{failure}"
    );
    assert_eq!(admin.tx_state(), TxState::Idle);
    assert_eq!(
        scalar(
            &admin,
            &format!("SELECT count(*) FROM {SCHEMA}.kerno_test_k72_checked")
        )
        .await,
        "0"
    );
}

/// K72: an empty parent is refused before running; a failing row rolls the
/// whole insert back and is named.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn an_empty_parent_is_refused_and_a_failing_row_keeps_nothing() {
    in_scratch(REFUSALS, refusals()).await;
}
